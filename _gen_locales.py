from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(r"C:\split\app\src\main\res")
SRC = ROOT / "values" / "strings.xml"

# Language names stay native in all locales
LANG_NAMES = {
    "settings_language_en": "English",
    "settings_language_es": "Español",
    "settings_language_fr": "Français",
    "settings_language_de": "Deutsch",
    "settings_language_pt": "Português",
    "settings_language_hi": "हिन्दी",
    "settings_language_ja": "日本語",
}


def parse_strings(path: Path) -> list[tuple[str, str]]:
    text = path.read_text(encoding="utf-8")
    return re.findall(r'<string name="([^"]+)">(.*?)</string>', text, flags=re.DOTALL)


def write_locale(folder: str, translations: dict[str, str], ordered: list[tuple[str, str]]) -> int:
    out_dir = ROOT / folder
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    missing = []
    for name, _en in ordered:
        if name == "app_name":
            val = "SplitEase"
        elif name in LANG_NAMES:
            val = LANG_NAMES[name]
        elif name in translations:
            val = translations[name]
        else:
            missing.append(name)
            continue
        lines.append(f'    <string name="{name}">{val}</string>')
    lines.append("</resources>")
    lines.append("")
    (out_dir / "strings.xml").write_text("\n".join(lines), encoding="utf-8")
    if missing:
        raise SystemExit(f"{folder}: missing {len(missing)} keys: {missing[:20]}")
    return len(ordered)


